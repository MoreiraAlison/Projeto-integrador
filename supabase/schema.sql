create table if not exists usuarios (
  id bigint generated by default as identity primary key,
  nome text not null,
  email text not null unique,
  senha text not null,
  telefone text,
  tipo text not null,
  cargo text,
  ativo boolean default true,
  criado_em timestamptz default now()
);

create table if not exists alunos (
  id bigint generated by default as identity primary key,
  nome text not null,
  turma text,
  serie text,
  usuario_id bigint unique references usuarios(id),
  responsavel_id bigint references usuarios(id)
);

create table if not exists profissionais (
  id bigint generated by default as identity primary key,
  usuario_id bigint unique references usuarios(id),
  especialidade text,
  sala text,
  horario_inicio text,
  horario_fim text
);

create table if not exists agendamentos (
  id bigint generated by default as identity primary key,
  responsavel_id bigint references usuarios(id),
  profissional_id bigint references profissionais(id),
  aluno_id bigint references alunos(id),
  data date not null,
  hora time not null,
  motivo text,
  observacao text,
  status text default 'aguardando',
  criado_em timestamptz default now()
);

create table if not exists disponibilidade (
  id bigint generated by default as identity primary key,
  profissional_id bigint references profissionais(id) on delete cascade,
  dia_semana integer not null,
  hora_inicio time not null,
  hora_fim time not null
);

create table if not exists notificacoes (
  id bigint generated by default as identity primary key,
  usuario_id bigint references usuarios(id) on delete cascade,
  mensagem text not null,
  lida boolean default false,
  data timestamptz default now()
);

create table if not exists logs (
  id bigint generated by default as identity primary key,
  usuario_id bigint references usuarios(id),
  acao text,
  data timestamptz default now()
);

alter table usuarios enable row level security;
alter table alunos enable row level security;
alter table profissionais enable row level security;
alter table agendamentos enable row level security;
alter table disponibilidade enable row level security;
alter table notificacoes enable row level security;
alter table logs enable row level security;
